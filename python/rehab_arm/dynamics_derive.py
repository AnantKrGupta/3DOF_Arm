"""Symbolic Euler-Lagrange derivation of the 3-DOF arm dynamics (SymPy).

    M(q) qdd + C(q, qd) qd + G(q) + B qd = tau

* Links: upper arm (DH body 2) and forearm+hand (DH body 3) are solid
  cylinders of radius r_i, COM at c_i * L_i from the proximal joint.
* Payload: point mass mp at the end effector (DH frame 3 origin).
* Gravity acts along world -Z  ==  +x0 in the DH base frame.
* C is built from Christoffel symbols, so (Mdot - 2C) is skew-symmetric.

Running this module generates
    python/rehab_arm/_dynamics_generated.py   (vectorised NumPy)
    matlab/generated/arm_M.m, arm_C.m, arm_G.m, arm_energy.m (codegen-ready)
"""
from __future__ import annotations

import pathlib
import time

import sympy as sp

from .params import DYN_PARAM_NAMES, ROOT


def _dh(a, alpha, d, theta):
    ct, st = sp.cos(theta), sp.sin(theta)
    ca, sa = sp.cos(alpha), sp.sin(alpha)
    return sp.Matrix([[ct, -st * ca, st * sa, a * ct],
                      [st, ct * ca, -ct * sa, a * st],
                      [0, sa, ca, d],
                      [0, 0, 0, 1]])


def derive(verbose: bool = True):
    t0 = time.time()
    q = sp.Matrix(sp.symbols("q1:4", real=True))
    qd = sp.Matrix(sp.symbols("qd1:4", real=True))
    L1, L2, c1, c2, m1, m2, mp, r1, r2, g = sp.symbols(" ".join(DYN_PARAM_NAMES), positive=True)
    P = [L1, L2, c1, c2, m1, m2, mp, r1, r2, g]

    T01 = _dh(0, sp.pi / 2, 0, q[0])
    T12 = _dh(L1, 0, 0, q[1])
    T23 = _dh(L2, 0, 0, q[2])
    T02 = T01 * T12
    T03 = T02 * T23

    # COM positions in frame 0 (links lie along -x_i of their distal frame i)
    pc1 = (T02 * sp.Matrix([-(1 - c1) * L1, 0, 0, 1]))[:3, 0]
    pc2 = (T03 * sp.Matrix([-(1 - c2) * L2, 0, 0, 1]))[:3, 0]
    pe = T03[:3, 3]

    z0 = sp.Matrix([0, 0, 1])
    z1 = T01[:3, 2]
    z2 = T02[:3, 2]
    zero = sp.zeros(3, 1)
    Jw_upper = sp.Matrix.hstack(z0, z1, zero)
    Jw_fore = sp.Matrix.hstack(z0, z1, z2)

    Jv_upper = pc1.jacobian(q)
    Jv_fore = pc2.jacobian(q)
    Jv_pay = pe.jacobian(q)

    def cyl_inertia(m, r, L):  # about COM, axis along local x
        return sp.diag(m * r**2 / 2, m * (3 * r**2 + L**2) / 12, m * (3 * r**2 + L**2) / 12)

    R02, R03 = T02[:3, :3], T03[:3, :3]
    I1 = R02 * cyl_inertia(m1, r1, L1) * R02.T
    I2 = R03 * cyl_inertia(m2, r2, L2) * R03.T

    M = (m1 * Jv_upper.T * Jv_upper + Jw_upper.T * I1 * Jw_upper
         + m2 * Jv_fore.T * Jv_fore + Jw_fore.T * I2 * Jw_fore
         + mp * Jv_pay.T * Jv_pay)
    M = M.applyfunc(lambda e: sp.trigsimp(sp.expand(e)))
    if verbose:
        print(f"[derive] M done ({time.time() - t0:.1f}s)")

    # Potential energy: gravity vector in frame 0 is +g x0
    V = -g * (m1 * pc1[0] + m2 * pc2[0] + mp * pe[0])
    V = sp.simplify(V)
    G = sp.Matrix([sp.diff(V, qi) for qi in q]).applyfunc(sp.simplify)

    # Coriolis / centrifugal via Christoffel symbols
    n = 3
    C = sp.zeros(n, n)
    for k in range(n):
        for j in range(n):
            s = 0
            for i in range(n):
                s += sp.Rational(1, 2) * (sp.diff(M[k, j], q[i]) + sp.diff(M[k, i], q[j])
                                          - sp.diff(M[i, j], q[k])) * qd[i]
            C[k, j] = sp.simplify(s)
    if verbose:
        print(f"[derive] C, G done ({time.time() - t0:.1f}s)")

    KE = sp.simplify((qd.T * M * qd)[0] / 2)
    return dict(q=q, qd=qd, P=P, M=M, C=C, G=G, V=V, KE=KE, pe=pe)


# ------------------------------------------------------------------ codegen
def _subs_maps(d):
    q, qd, P = d["q"], d["qd"], d["P"]
    py = {q[i]: sp.Symbol(f"q_{i}") for i in range(3)}
    py.update({qd[i]: sp.Symbol(f"qd_{i}") for i in range(3)})
    py.update({P[i]: sp.Symbol(f"P_{i}") for i in range(len(P))})
    return py


def _py_body(exprs, shape, d, sym_out="out"):
    rep = _subs_maps(d)
    exprs = [sp.sympify(e).xreplace(rep) for e in exprs]
    sub, red = sp.cse(exprs, symbols=sp.numbered_symbols("x"))
    lines = []
    for s, e in sub:
        lines.append(f"    {s} = {sp.pycode(e, fully_qualified_modules=False)}")
    idx = [(i, j) for i in range(shape[0]) for j in range(shape[1])] if len(shape) == 2 else [(i,) for i in range(shape[0])]
    for k, e in zip(idx, red):
        ix = ", ".join(str(v) for v in k)
        lines.append(f"    {sym_out}[..., {ix}] = {sp.pycode(e, fully_qualified_modules=False)}")
    return "\n".join(lines)


PY_HEADER = '''"""AUTO-GENERATED by rehab_arm.dynamics_derive -- do not edit.

Vectorised over leading dimensions: q, qd shape (..., 3); P = dynamic
parameter vector {names}.
"""
import numpy as np
from numpy import sin, cos, sqrt, pi  # noqa: F401


def _unpack(q, qd, P):
    q = np.asarray(q, float); qd = np.asarray(qd, float); P = np.asarray(P, float)
    return (q[..., 0], q[..., 1], q[..., 2], qd[..., 0], qd[..., 1], qd[..., 2], *P)

'''


def generate_python(d, path: pathlib.Path):
    names = ", ".join(f"P_{i}" for i in range(len(d["P"])))
    unpack = f"    q_0, q_1, q_2, qd_0, qd_1, qd_2, {names} = _unpack(q, qd, P)"
    src = PY_HEADER.format(names=DYN_PARAM_NAMES)
    src += "\ndef mass_matrix(q, P):\n" + unpack.replace("qd, P", "np.zeros(3), P") + \
        "\n    out = np.zeros(np.shape(q)[:-1] + (3, 3))\n" + \
        _py_body(list(d["M"]), (3, 3), d) + "\n    return out\n\n"
    src += "\ndef coriolis_matrix(q, qd, P):\n" + unpack + \
        "\n    out = np.zeros(np.shape(q)[:-1] + (3, 3))\n" + \
        _py_body(list(d["C"]), (3, 3), d) + "\n    return out\n\n"
    src += "\ndef gravity_vector(q, P):\n" + unpack.replace("qd, P", "np.zeros(3), P") + \
        "\n    out = np.zeros(np.shape(q)[:-1] + (3,))\n" + \
        _py_body(list(d["G"]), (3,), d) + "\n    return out\n\n"
    src += "\ndef energy(q, qd, P):\n" + unpack + \
        "\n    out = np.zeros(np.shape(q)[:-1] + (2,))\n" + \
        _py_body([d["KE"], d["V"]], (2,), d) + "\n    return out\n"
    path.write_text(src)


def _m_body(exprs, shape, d, out="out"):
    q, qd, P = d["q"], d["qd"], d["P"]
    rep = {q[i]: sp.Symbol(f"q{i + 1}") for i in range(3)}
    rep.update({qd[i]: sp.Symbol(f"qd{i + 1}") for i in range(3)})
    exprs = [sp.sympify(e).xreplace(rep) for e in exprs]
    sub, red = sp.cse(exprs, symbols=sp.numbered_symbols("t"))
    lines = []
    for s, e in sub:
        lines.append(f"{sp.octave_code(e, assign_to=str(s))}")
    idx = [(i, j) for i in range(shape[0]) for j in range(shape[1])] if len(shape) == 2 else [(i, 0) for i in range(shape[0])]
    for (i, j), e in zip(idx, red):
        lines.append(f"{out}({i + 1},{j + 1}) = {sp.octave_code(e)};")
    return "\n".join(lines)


def _m_unpack(with_qd: bool):
    s = "q1 = q(1); q2 = q(2); q3 = q(3);\n"
    if with_qd:
        s += "qd1 = qd(1); qd2 = qd(2); qd3 = qd(3);\n"
    s += "".join(f"{n} = P({i + 1}); " for i, n in enumerate(DYN_PARAM_NAMES)) + "\n"
    return s


def generate_matlab(d, folder: pathlib.Path):
    folder.mkdir(parents=True, exist_ok=True)
    hdr = ("%% AUTO-GENERATED by python/rehab_arm/dynamics_derive.py (SymPy Euler-Lagrange).\n"
           f"%% P = [{' '.join(DYN_PARAM_NAMES)}]\n%#codegen\n")
    specs = [
        ("arm_M", "out = arm_M(q, P)", False, list(d["M"]), (3, 3), "Mass matrix M(q)"),
        ("arm_C", "out = arm_C(q, qd, P)", True, list(d["C"]), (3, 3), "Coriolis matrix C(q,qd) (Christoffel)"),
        ("arm_G", "out = arm_G(q, P)", False, list(d["G"]), (3, 1), "Gravity vector G(q)"),
        ("arm_energy", "out = arm_energy(q, qd, P)", True, [d["KE"], d["V"]], (2, 1), "[kinetic; potential] energy"),
    ]
    for name, sig, wqd, exprs, shape, doc in specs:
        body = _m_body(exprs, shape, d)
        txt = (f"function {sig}\n%{name.upper()} {doc}\n{hdr}"
               f"{_m_unpack(wqd)}out = zeros({shape[0]},{shape[1]});\n{body}\nend\n")
        (folder / f"{name}.m").write_text(txt)


def main():
    d = derive()
    py_path = ROOT / "python" / "rehab_arm" / "_dynamics_generated.py"
    generate_python(d, py_path)
    generate_matlab(d, ROOT / "matlab" / "generated")
    # Human-readable equations for the report
    eq = ROOT / "results" / "dynamics_equations.txt"
    eq.parent.mkdir(exist_ok=True)
    with open(eq, "w") as f:
        f.write("Euler-Lagrange dynamics  M(q) qdd + C(q,qd) qd + G(q) = tau\n\n")
        for i in range(3):
            for j in range(3):
                f.write(f"M[{i+1},{j+1}] = {d['M'][i, j]}\n")
        f.write("\n")
        for i in range(3):
            f.write(f"G[{i+1}] = {d['G'][i]}\n")
        f.write("\n")
        for i in range(3):
            for j in range(3):
                f.write(f"C[{i+1},{j+1}] = {d['C'][i, j]}\n")
    print(f"[derive] wrote {py_path}\n[derive] wrote matlab/generated/*.m\n[derive] wrote {eq}")


if __name__ == "__main__":
    main()
