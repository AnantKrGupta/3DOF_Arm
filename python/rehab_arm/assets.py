"""Export the arm as URDF and as a physics-ready USD articulation.

Both are generated from config/arm_params.json, so the Isaac Sim digital
twin has *exactly* the kinematic/inertial parameters used in the
Lagrangian model. Joint frames are set up so Isaac joint angles == DH q.

    q = 0  -> arm hanging down;  j1 axis +X (abduction),
    j2, j3 axis -Y (flexion, elbow) -> same signs as the DH convention.
"""
from __future__ import annotations

import math
import pathlib

import numpy as np

from .params import ArmParams, ROOT, load_params

ASSET_DIR = ROOT / "isaac" / "assets"
DRIVE_KP = 400.0      # Nm/rad  (position drive of the twin)
DRIVE_KD = 30.0       # Nm s/rad
SHOULDER_HOUSING = dict(mass=0.05, inertia=2e-5)


def cyl_inertia_z(m, r, L):
    """Solid cylinder with axis along z, about its COM."""
    ixx = m * (3 * r * r + L * L) / 12.0
    return np.array([ixx, ixx, 0.5 * m * r * r])


def forearm_with_payload(p: ArmParams):
    """Merge forearm cylinder + point payload at the hand into one rigid body.
    Frame origin at the elbow, link along -z."""
    m = p.m2 + p.mp
    z_f, z_p = -p.c2 * p.L2, -p.L2
    zc = (p.m2 * z_f + p.mp * z_p) / m
    I = cyl_inertia_z(p.m2, p.r2, p.L2)
    d_f, d_p = z_f - zc, z_p - zc
    I = I + np.array([p.m2 * d_f**2 + p.mp * d_p**2] * 2 + [0.0])
    return m, zc, I


def write_urdf(p: ArmParams, path: pathlib.Path):
    I1 = cyl_inertia_z(p.m1, p.r1, p.L1)
    I2 = cyl_inertia_z(p.m2, p.r2, p.L2)
    lim = p.limits
    sx, sy, sz = p.shoulder_pos
    names = p.joint_names

    def inertial(m, z, I):
        return (f'<inertial><origin xyz="0 0 {z:.6f}"/><mass value="{m:.6f}"/>'
                f'<inertia ixx="{I[0]:.8f}" iyy="{I[1]:.8f}" izz="{I[2]:.8f}" ixy="0" ixz="0" iyz="0"/></inertial>')

    def cyl(L, r, rgba):
        g = f'<geometry><cylinder radius="{r}" length="{L}"/></geometry>'
        return (f'<visual><origin xyz="0 0 {-L / 2:.6f}"/>{g}<material name="m{rgba}"><color rgba="{rgba}"/></material></visual>'
                f'<collision><origin xyz="0 0 {-L / 2:.6f}"/>{g}</collision>')

    def joint(name, parent, child, xyz, axis, k):
        return (f'<joint name="{name}" type="revolute"><parent link="{parent}"/><child link="{child}"/>'
                f'<origin xyz="{xyz}" rpy="0 0 0"/><axis xyz="{axis}"/>'
                f'<limit lower="{lim[k, 0]:.6f}" upper="{lim[k, 1]:.6f}" effort="{p.tau_max[k]}" velocity="{p.qdot_max[k]:.4f}"/>'
                f'<dynamics damping="{p.viscous[k]}" friction="0"/></joint>')

    hs = SHOULDER_HOUSING
    urdf = f"""<?xml version="1.0"?>
<!-- AUTO-GENERATED by python/rehab_arm/assets.py from config/arm_params.json -->
<robot name="{p.raw['name']}">
  <link name="world"/>
  <joint name="world_fixed" type="fixed"><parent link="world"/><child link="base_link"/><origin xyz="{sx} {sy} {sz}"/></joint>
  <link name="base_link">
    {inertial(1.0, 0.0, [1e-3] * 3)}
    <visual><geometry><box size="0.08 0.12 0.08"/></geometry><material name="grey"><color rgba="0.4 0.4 0.45 1"/></material></visual>
  </link>
  <link name="shoulder_link">{inertial(hs['mass'], 0.0, [hs['inertia']] * 3)}
    <visual><geometry><sphere radius="0.045"/></geometry><material name="joint"><color rgba="0.15 0.15 0.15 1"/></material></visual></link>
  <link name="upper_arm">{inertial(p.m1, -p.c1 * p.L1, I1)}{cyl(p.L1, p.r1, "0.2 0.45 0.85 1")}</link>
  <link name="forearm">{inertial(p.m2, -p.c2 * p.L2, I2)}{cyl(p.L2, p.r2, "0.25 0.65 0.9 1")}</link>
  <link name="hand">{inertial(p.mp, 0.0, [1e-6] * 3)}
    <visual><geometry><sphere radius="0.04"/></geometry><material name="hand"><color rgba="0.9 0.75 0.6 1"/></material></visual></link>
  {joint(names[0], "base_link", "shoulder_link", "0 0 0", "1 0 0", 0)}
  {joint(names[1], "shoulder_link", "upper_arm", "0 0 0", "0 -1 0", 1)}
  {joint(names[2], "upper_arm", "forearm", f"0 0 {-p.L1}", "0 -1 0", 2)}
  <joint name="hand_fixed" type="fixed"><parent link="forearm"/><child link="hand"/><origin xyz="0 0 {-p.L2}"/></joint>
</robot>
"""
    path.write_text(urdf)


def write_usd(p: ArmParams, path: pathlib.Path):
    from pxr import Gf, Sdf, Usd, UsdGeom, UsdPhysics

    stage = Usd.Stage.CreateNew(str(path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    UsdPhysics.SetStageKilogramsPerUnit(stage, 1.0)
    root = UsdGeom.Xform.Define(stage, "/rehab_arm")
    stage.SetDefaultPrim(root.GetPrim())
    UsdPhysics.ArticulationRootAPI.Apply(root.GetPrim())

    def body(name, pos, mass, com, inertia):
        x = UsdGeom.Xform.Define(stage, f"/rehab_arm/{name}")
        x.AddTranslateOp().Set(Gf.Vec3d(*pos))
        prim = x.GetPrim()
        UsdPhysics.RigidBodyAPI.Apply(prim)
        m = UsdPhysics.MassAPI.Apply(prim)
        m.CreateMassAttr(float(mass))
        m.CreateCenterOfMassAttr(Gf.Vec3f(*map(float, com)))
        m.CreateDiagonalInertiaAttr(Gf.Vec3f(*map(float, inertia)))
        m.CreatePrincipalAxesAttr(Gf.Quatf(1, 0, 0, 0))
        return prim

    def geom(parent, name, kind, color, collide=True, **kw):
        path_ = parent.GetPath().AppendChild(name)
        if kind == "cyl":
            g = UsdGeom.Cylinder.Define(stage, path_)
            g.CreateRadiusAttr(kw["r"]); g.CreateHeightAttr(kw["h"]); g.CreateAxisAttr("Z")
            ext = [(-kw["r"], -kw["r"], -kw["h"] / 2), (kw["r"], kw["r"], kw["h"] / 2)]
        elif kind == "sphere":
            g = UsdGeom.Sphere.Define(stage, path_)
            g.CreateRadiusAttr(kw["r"]); ext = [(-kw["r"],) * 3, (kw["r"],) * 3]
        else:
            g = UsdGeom.Cube.Define(stage, path_)
            g.CreateSizeAttr(1.0); ext = [(-0.5,) * 3, (0.5,) * 3]
        g.CreateExtentAttr(ext)
        g.CreateDisplayColorAttr([Gf.Vec3f(*color)])
        xf = UsdGeom.Xformable(g)
        if "offset" in kw:
            xf.AddTranslateOp().Set(Gf.Vec3d(*kw["offset"]))
        if "scale" in kw:
            xf.AddScaleOp().Set(Gf.Vec3f(*kw["scale"]))
        if collide:
            UsdPhysics.CollisionAPI.Apply(g.GetPrim())
        return g

    L1, L2 = p.L1, p.L2
    hs = SHOULDER_HOUSING
    base = body("base_link", (0, 0, 0), 1.0, (0, 0, 0), (1e-3,) * 3)
    geom(base, "housing", "cube", (0.4, 0.4, 0.45), collide=False, scale=(0.08, 0.12, 0.08), offset=(-0.06, 0, 0))
    shoulder = body("shoulder_link", (0, 0, 0), hs["mass"], (0, 0, 0), (hs["inertia"],) * 3)
    geom(shoulder, "joint_ball", "sphere", (0.15, 0.15, 0.15), collide=False, r=0.045)
    upper = body("upper_arm", (0, 0, 0), p.m1, (0, 0, -p.c1 * L1), cyl_inertia_z(p.m1, p.r1, L1))
    geom(upper, "link", "cyl", (0.2, 0.45, 0.85), r=p.r1, h=L1, offset=(0, 0, -L1 / 2))
    mf, zc, If = forearm_with_payload(p)
    fore = body("forearm", (0, 0, -L1), mf, (0, 0, zc), If)
    geom(fore, "link", "cyl", (0.25, 0.65, 0.9), r=p.r2, h=L2, offset=(0, 0, -L2 / 2))
    geom(fore, "elbow_ball", "sphere", (0.15, 0.15, 0.15), collide=False, r=0.04)
    geom(fore, "hand", "sphere", (0.9, 0.75, 0.6), r=0.04, offset=(0, 0, -L2))
    ee = UsdGeom.Xform.Define(stage, fore.GetPath().AppendChild("ee_frame"))
    ee.AddTranslateOp().Set(Gf.Vec3d(0, 0, -L2))

    # no self-collision inside the arm
    bodies = [base, shoulder, upper, fore]
    for b in bodies:
        fp = UsdPhysics.FilteredPairsAPI.Apply(b)
        fp.CreateFilteredPairsRel().SetTargets([o.GetPath() for o in bodies if o != b])

    # fix the base to the world
    fj = UsdPhysics.FixedJoint.Define(stage, "/rehab_arm/root_joint")
    fj.CreateBody1Rel().SetTargets([base.GetPath()])

    flip = Gf.Quatf(0, 0, 0, 1)   # Rz(180 deg): joint +Y  ->  body -Y
    ident = Gf.Quatf(1, 0, 0, 0)
    specs = [(p.joint_names[0], base, shoulder, (0, 0, 0), (0, 0, 0), "X", ident),
             (p.joint_names[1], shoulder, upper, (0, 0, 0), (0, 0, 0), "Y", flip),
             (p.joint_names[2], upper, fore, (0, 0, -L1), (0, 0, 0), "Y", flip)]
    UsdGeom.Scope.Define(stage, "/rehab_arm/joints")
    for k, (name, b0, b1, lp0, lp1, axis, rot) in enumerate(specs):
        j = UsdPhysics.RevoluteJoint.Define(stage, f"/rehab_arm/joints/{name}")
        j.CreateBody0Rel().SetTargets([b0.GetPath()])
        j.CreateBody1Rel().SetTargets([b1.GetPath()])
        j.CreateLocalPos0Attr(Gf.Vec3f(*lp0)); j.CreateLocalPos1Attr(Gf.Vec3f(*lp1))
        j.CreateLocalRot0Attr(rot); j.CreateLocalRot1Attr(rot)
        j.CreateAxisAttr(axis)
        j.CreateLowerLimitAttr(float(math.degrees(p.limits[k, 0])))
        j.CreateUpperLimitAttr(float(math.degrees(p.limits[k, 1])))
        d = UsdPhysics.DriveAPI.Apply(j.GetPrim(), "angular")
        d.CreateTypeAttr("force")
        d.CreateStiffnessAttr(DRIVE_KP * math.pi / 180.0)   # USD angular drive units: per degree
        d.CreateDampingAttr(DRIVE_KD * math.pi / 180.0)
        d.CreateMaxForceAttr(float(p.tau_max[k]))
        d.CreateTargetPositionAttr(0.0)
    root.GetPrim().SetCustomDataByKey("generated_from", "config/arm_params.json")
    stage.GetRootLayer().Save()


def export_all(params: ArmParams | None = None):
    p = params or load_params()
    ASSET_DIR.mkdir(parents=True, exist_ok=True)
    write_urdf(p, ASSET_DIR / "rehab_arm.urdf")
    try:
        write_usd(p, ASSET_DIR / "rehab_arm.usda")
    except ImportError:
        print("[assets] pxr not available (pip install usd-core); USD skipped")
    return ASSET_DIR


class UsdArticulationFK:
    """Traverse the USD articulation `/rehab_arm` and evaluate end-effector FK."""

    def __init__(self, usd_path: pathlib.Path | str | None = None, params: ArmParams | None = None):
        from pxr import Gf, Usd, UsdGeom, UsdPhysics

        self._Gf = Gf
        self.params = params or load_params()
        usd_path = pathlib.Path(usd_path) if usd_path else (ASSET_DIR / "rehab_arm.usda")
        self.stage = Usd.Stage.Open(str(usd_path))
        self.joints = []
        for jname in self.params.joint_names:
            prim = self.stage.GetPrimAtPath(f"/rehab_arm/joints/{jname}")
            if not prim.IsValid() or not prim.IsA(UsdPhysics.RevoluteJoint):
                raise RuntimeError(f"Missing UsdPhysics.RevoluteJoint at /rehab_arm/joints/{jname}")
            rj = UsdPhysics.RevoluteJoint(prim)
            J0 = self._joint_frame(rj.GetLocalPos0Attr().Get(), rj.GetLocalRot0Attr().Get())
            J1 = self._joint_frame(rj.GetLocalPos1Attr().Get(), rj.GetLocalRot1Attr().Get())
            self.joints.append({
                "name": jname,
                "body0": str(rj.GetBody0Rel().GetTargets()[0]),
                "body1": str(rj.GetBody1Rel().GetTargets()[0]),
                "axis": rj.GetAxisAttr().Get(),
                "J0": J0,
                "J1_inv": np.linalg.inv(J1),
            })
        ee_prim = self.stage.GetPrimAtPath("/rehab_arm/forearm/ee_frame")
        if not ee_prim.IsValid():
            raise RuntimeError("Missing /rehab_arm/forearm/ee_frame in USD stage")
        self.T_forearm_ee = np.array(
            UsdGeom.Xformable(ee_prim).GetLocalTransformation(Usd.TimeCode.Default()), dtype=float
        ).T

    def _joint_frame(self, pos, quat) -> np.ndarray:
        Gf = self._Gf
        mat = Gf.Matrix4d(Gf.Rotation(Gf.Quatd(quat)), Gf.Vec3d(*map(float, pos)))
        return np.array(mat, dtype=float).T

    def _axis_rot(self, axis: str, angle_rad: float) -> np.ndarray:
        Gf = self._Gf
        vec = {"X": Gf.Vec3d(1, 0, 0), "Y": Gf.Vec3d(0, 1, 0), "Z": Gf.Vec3d(0, 0, 1)}[axis]
        mat = Gf.Matrix4d(Gf.Rotation(vec, float(np.rad2deg(angle_rad))), Gf.Vec3d(0, 0, 0))
        return np.array(mat, dtype=float).T

    def body_transforms(self, q) -> dict[str, np.ndarray]:
        q = np.asarray(q, float)
        T_base = np.eye(4)
        T_base[:3, 3] = self.params.shoulder_pos
        frames = {"/rehab_arm/base_link": T_base}
        for k, j in enumerate(self.joints):
            T_rel = j["J0"] @ self._axis_rot(j["axis"], q[k]) @ j["J1_inv"]
            frames[j["body1"]] = frames[j["body0"]] @ T_rel
        frames["/rehab_arm/forearm/ee_frame"] = frames["/rehab_arm/forearm"] @ self.T_forearm_ee
        return frames

    def ee_world(self, q) -> np.ndarray:
        return self.body_transforms(q)["/rehab_arm/forearm/ee_frame"][:3, 3]

