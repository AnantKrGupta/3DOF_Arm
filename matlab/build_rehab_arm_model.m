function mdl = build_rehab_arm_model(mdl)
%BUILD_REHAB_ARM_MODEL Programmatically build the Simulink model
%   rehab_arm_3dof.slx :  Reference -> Controller (PID or LQR gains) ->
%   Lagrangian plant  M(q)qdd + C(q,qd)qd + G(q) + B qd = tau + tau_dist.
%
%   The plant / gravity-compensation blocks call the SymPy-generated,
%   codegen-ready functions in matlab/generated (arm_M, arm_C, arm_G).
%   Both controllers share one structure:
%       tau = G_hat(q_m) + Kp e + Ki z + Kd e_dot     (saturated, anti-windup)
%   PID -> diagonal gains (GA tuned), LQR -> full gain matrices (LQI design).
if nargin < 1, mdl = 'rehab_arm_3dof'; end
here = fileparts(mfilename('fullpath'));
addpath(here, fullfile(here, 'generated'));
if bdIsLoaded(mdl), close_system(mdl, 0); end
slx = fullfile(here, [mdl '.slx']);
if exist(slx, 'file'), delete(slx); end

new_system(mdl);
set_param(mdl, 'Solver', 'ode4', 'FixedStep', 'Ts', 'StopTime', 'Tsim', ...
    'SaveTime', 'off', 'SaveOutput', 'off', 'ReturnWorkspaceOutputs', 'on', ...
    'SignalLogging', 'off');

% ------------------------------------------------------------- blocks
add_block('simulink/Sources/Clock', [mdl '/Clock'], 'Position', [30 40 60 70]);
mfb(mdl, 'Reference', [120 25 230 85], ...
    sprintf(['function [qr, qrd] = fcn(t)\n' ...
             '%% min-jerk rehab task (rehab_task.m)\n' ...
             '[qr, qrd, ~] = rehab_task(t);\n']));

mfb(mdl, 'Controller', [400 40 560 330], sprintf([ ...
    'function [tau, zdot] = fcn(qr, qrd, q, qd, z, Kp, Ki, Kd, Pm, tau_max, nq, nqd)\n' ...
    '%% Gravity-compensated PID / LQI with saturation + conditional-integration anti-windup\n' ...
    'qm  = q(:)  + nq(:);      %% encoder noise\n' ...
    'qdm = qd(:) + nqd(:);     %% velocity-estimate noise\n' ...
    'e   = qr(:)  - qm;\n' ...
    'ed  = qrd(:) - qdm;\n' ...
    'tau_u = arm_G(qm, Pm(:)) + Kp*e + Ki*z(:) + Kd*ed;\n' ...
    'tau = min(max(tau_u, -tau_max(:)), tau_max(:));\n' ...
    'zdot = e .* double(abs(tau_u) <= tau_max(:));\n']));

mfb(mdl, 'Lagrangian Plant', [760 120 900 280], sprintf([ ...
    'function qdd = fcn(q, qd, tau, Pt, Bv, t, dist)\n' ...
    '%% Euler-Lagrange forward dynamics of the TRUE arm (may differ from model Pm)\n' ...
    'q = q(:); qd = qd(:); Pt = Pt(:);\n' ...
    'td = zeros(3,1);\n' ...
    'for i = 1:size(dist,1)\n' ...
    '    j = round(dist(i,3));\n' ...
    '    if t >= dist(i,1) && t < dist(i,2) && j >= 1 && j <= 3\n' ...
    '        td(j) = td(j) + dist(i,4);\n' ...
    '    end\n' ...
    'end\n' ...
    'rhs = tau(:) + td - arm_C(q, qd, Pt)*qd - arm_G(q, Pt) - Bv(:).*qd;\n' ...
    'qdd = arm_M(q, Pt) \\ rhs;\n']));

add_block('simulink/Continuous/Integrator', [mdl '/Int_qd'], 'InitialCondition', 'zeros(3,1)', ...
    'Position', [960 185 990 215]);
add_block('simulink/Continuous/Integrator', [mdl '/Int_q'], 'InitialCondition', 'q0', ...
    'Position', [1040 185 1070 215]);
add_block('simulink/Continuous/Integrator', [mdl '/Int_z'], 'InitialCondition', 'zeros(3,1)', ...
    'Position', [620 270 650 300]);

consts = {'Kp', 'Ki', 'Kd', 'Pm', 'tau_max'};
for k = 1:numel(consts)
    add_block('simulink/Sources/Constant', [mdl '/' consts{k}], 'Value', consts{k}, ...
        'VectorParams1D', 'off', 'Position', [250 140+30*(k-1) 330 160+30*(k-1)]);
end
add_block('simulink/Sources/Constant', [mdl '/Pt'], 'Value', 'Pt', 'VectorParams1D', 'off', ...
    'Position', [620 330 680 350]);
add_block('simulink/Sources/Constant', [mdl '/Bv'], 'Value', 'Bv', 'VectorParams1D', 'off', ...
    'Position', [620 360 680 380]);
add_block('simulink/Sources/Constant', [mdl '/dist'], 'Value', 'dist', 'VectorParams1D', 'off', ...
    'Position', [620 420 680 440]);
add_block('simulink/Sources/Random Number', [mdl '/noise_q'], 'Mean', '0', ...
    'Variance', 'noise_q^2*ones(3,1)', 'Seed', '[11 12 13]', 'SampleTime', 'Ts', ...
    'Position', [250 300 300 330]);
add_block('simulink/Sources/Random Number', [mdl '/noise_qd'], 'Mean', '0', ...
    'Variance', 'noise_qd^2*ones(3,1)', 'Seed', '[21 22 23]', 'SampleTime', 'Ts', ...
    'Position', [250 345 300 375]);

logs = {'t_log', 'q_log', 'qr_log', 'tau_log'};
for k = 1:numel(logs)
    add_block('simulink/Sinks/To Workspace', [mdl '/' logs{k}], 'VariableName', logs{k}, ...
        'SaveFormat', 'Array', 'Position', [1150 40+60*(k-1) 1220 70+60*(k-1)]);
end

% ------------------------------------------------------------- wiring
L = @(a, b) add_line(mdl, a, b, 'autorouting', 'smart');
L('Clock/1', 'Reference/1');
L('Reference/1', 'Controller/1');
L('Reference/2', 'Controller/2');
L('Int_q/1', 'Controller/3');
L('Int_qd/1', 'Controller/4');
L('Int_z/1', 'Controller/5');
for k = 1:numel(consts), L([consts{k} '/1'], sprintf('Controller/%d', 5 + k)); end
L('noise_q/1', 'Controller/11');
L('noise_qd/1', 'Controller/12');
L('Controller/2', 'Int_z/1');
L('Int_q/1', 'Lagrangian Plant/1');
L('Int_qd/1', 'Lagrangian Plant/2');
L('Controller/1', 'Lagrangian Plant/3');
L('Pt/1', 'Lagrangian Plant/4');
L('Bv/1', 'Lagrangian Plant/5');
L('Clock/1', 'Lagrangian Plant/6');
L('dist/1', 'Lagrangian Plant/7');
L('Lagrangian Plant/1', 'Int_qd/1');
L('Int_qd/1', 'Int_q/1');
L('Clock/1', 't_log/1');
L('Int_q/1', 'q_log/1');
L('Reference/1', 'qr_log/1');
L('Controller/1', 'tau_log/1');

add_block('built-in/Note', [mdl '/note'], 'Position', [40 470], 'Text', ...
    ['3-DOF rehab arm: Euler-Lagrange plant (SymPy-generated M, C, G) + gravity-compensated ' ...
     'PID (GA-tuned) / LQI controller. Variables are supplied by default_sim_vars.m']);
save_system(mdl, slx);
fprintf('Built %s\n', slx);
end

function mfb(mdl, name, pos, code)
blk = [mdl '/' name];
add_block('simulink/User-Defined Functions/MATLAB Function', blk, 'Position', pos);
cfg = get_param(blk, 'MATLABFunctionConfiguration');
cfg.FunctionScript = code;
end
